/** Match stored nationality text to a country name for the select, if possible */
export function resolveNationalitySelectValue(input?: string): string {
  const trimmed = input?.trim();
  if (!trimmed) return "";
  const exact = _NATIONALITIES_LIST.find(
    (n) =>
      n.name.toLowerCase() === trimmed.toLowerCase() ||
      n.nationality.toLowerCase() === trimmed.toLowerCase(),
  );
  return exact?.name ?? "";
}
